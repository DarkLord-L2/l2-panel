-- L2 Clan Cabinet — «Раздача»: точный список мероприятий вместо одного диапазона дат.
-- «ДКП Соло»/«ДКП Пати» теперь позволяют снять галочкой отдельные мероприятия внутри периода
-- (например, пропустить осаду посреди двух недель). Кнопка «Раздать» кладёт в payout_batches
-- список выбранных мероприятий, а «Раздача» считает «кто у какого лидера сколько раз был» ровно по нему.
-- Без этой колонки всё продолжает работать по датам, как раньше.
-- Выполнить в Supabase Dashboard → SQL Editor (после schema_payout_batches.sql)

alter table public.payout_batches add column if not exists event_ids jsonb;

-- unit_by_nick — цена ОДНОГО КМ на человека из «ДКП» (доля × % буста × коэффициент). «Раздача» платит
-- «число КМ у лидера × цена»: человек получает деньги от того лидера, у которого был в этот день.
alter table public.payout_batches add column if not exists unit_by_nick jsonb;
