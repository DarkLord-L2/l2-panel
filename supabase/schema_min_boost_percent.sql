-- L2 Clan Cabinet — «Минимальный % буста»: единая нижняя граница % буста на весь
-- клан (1-100), настраивается в Админ-панели → «ДКП». Применяется ТОЛЬКО к тем,
-- у кого в «Проверке буста» вообще не отмечено ни одного пункта (реальный балл = 0):
-- вместо 0% показывается и используется в «ДКП Соло»/«ДКП Пати» этот минимум.
-- Как только у человека отмечен хотя бы один пункт буста — минимум полностью
-- отменяется, используется его реальный посчитанный процент (даже если он ниже
-- минимума) — приоритет всегда у реального значения, минимум не подмешивается.
-- 0 — минимум выключен (ведёт себя как раньше, 0% при пустом бусте).
-- Выполнить в Supabase Dashboard → SQL Editor (после schema_loot_split_settings.sql)

alter table public.loot_split_settings
  add column if not exists min_boost_percent numeric not null default 0;
